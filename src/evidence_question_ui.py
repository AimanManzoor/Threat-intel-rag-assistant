"""Question form for exact-CVE evidence lookup; no LLM calls."""
import json
from src.evidence_question import run_question


def render_question_search(root, artifact_sha256):
    import streamlit as st

    st.markdown("### Ask for source reports")
    st.caption(
        "Exact-CVE source lookup only. Example: Which reports mention CVE-2025-20333? "
        "A bare CVE also works. Actor attribution, exclusions and multiple CVEs require clarification."
    )
    with st.form("graph_question_form"):
        question = st.text_input("CVE source question", max_chars=1000,
                                 key="graph_source_question",
                                 placeholder="Which reports mention CVE-2025-20333?")
        submitted = st.form_submit_button("Find source reports")
    key = (artifact_sha256, question.strip())
    if submitted:
        st.session_state["graph_question_result"] = (key, run_question(question, root=root))
    stored = st.session_state.get("graph_question_result")
    if stored is None or stored[0] != key:
        return
    report = stored[1]
    if report["status"] in {"completed", "no_matches"}:
        st.info(report["message"])
    elif report["status"] in {"clarification_required", "rejected"}:
        st.warning(report["message"])
    else:
        st.error(report["message"])
    for source in report["sources"]:
        st.markdown("**Source report**")
        st.text(source["report_title"])
        st.code(source["source_file"] + ":" + source["source_location"], language=None)
        st.text(source["excerpt"])
    st.caption(
        "This summary is assembled from verified mention records, not generated by a model. "
        "It does not establish exploitation or the truth of a threat claim. Human review remains required."
    )
    with st.expander("Inspect source-question plan and result"):
        st.json(report)
    st.download_button(
        "Download source lookup result", json.dumps(report, indent=2),
        file_name="threat_source_lookup.json", mime="application/json",
        key="download_source_lookup",
    )

    if report["status"] in {"completed", "no_matches"}:
        from src.analyst_brief import make_brief
        st.download_button(
            "Download analyst evidence brief",
            make_brief(report),
            file_name="threat_analyst_brief.txt",
            mime="text/plain",
            key="download_analyst_brief",
        )
